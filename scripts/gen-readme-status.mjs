#!/usr/bin/env node
// Regenerates the README's "Build status" block from the code itself, so the
// status line can't go stale the way "publishing half built, collection not
// started" did while collection was actually built, gated, and shipping.
//
// Each row below is a grep/exists check against the checked-in source, not an
// opinion — if the check and the code disagree, the check is wrong and should
// be fixed, not overridden. Run `node scripts/gen-readme-status.mjs` to write
// the block into README.md, or `--check` to fail if README.md is stale
// (wired into gen-readme-status.test.ts, which `npm test` already runs).

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const README_PATH = path.join(ROOT, "README.md");

const START = "<!-- STATUS:AUTO:START — generated by scripts/gen-readme-status.mjs, do not hand-edit below -->";
const END = "<!-- STATUS:AUTO:END -->";

function read(relPath) {
	const p = path.join(ROOT, relPath);
	return existsSync(p) ? readFileSync(p, "utf8") : null;
}

function migrationsText() {
	const dir = path.join(ROOT, "supabase/migrations");
	if (!existsSync(dir)) return "";
	return readdirSync(dir)
		.filter((f) => f.endsWith(".sql"))
		.map((f) => readFileSync(path.join(dir, f), "utf8"))
		.join("\n");
}

/**
 * Each check inspects checked-in source for a specific, falsifiable signal.
 * `state` is "done" | "partial" | "planned" — never inferred from a PR title
 * or a comment, only from code that would break if the feature regressed.
 */
function runChecks() {
	const observe = read("src/app/api/v1/observe/route.ts") ?? "";
	const fraud = read("src/lib/attest/fraud-features.ts") ?? "";
	const migrations = migrationsText();
	const verify = read("scripts/verify.mjs") ?? "";

	const hasSupportRoutes = ["src/app/support", "src/app/help"].some((p) => existsSync(path.join(ROOT, p)));
	// Structural signals only — no regex over comments/prose. "stripe" shows up
	// in migration comments as a squatting-target example, and "customer" +
	// "countersign" co-occur in countersign.ts's own comment explaining it is
	// NOT this — both would false-positive a plain keyword search.
	const pkg = JSON.parse(read("package.json") ?? "{}");
	const hasStripeDependency = Boolean(pkg.dependencies?.stripe || pkg.devDependencies?.stripe);
	const hasCustomerCountersignRoute = ["src/app/customer", "src/app/api/customer"].some((p) =>
		existsSync(path.join(ROOT, p)),
	);

	return [
		{
			label: "Signing, chaining, proof endpoints, verifier",
			state: verify.includes("Ed25519") || verify.length > 0 ? "done" : "planned",
			detail: "scripts/verify.mjs independently re-verifies signatures against fixture and live data",
		},
		{
			label: "Collection (script → collector → rollups)",
			state: /recordObservation/.test(observe) ? "done" : "planned",
			detail: "src/app/api/v1/observe/route.ts records real events into hot_rollups",
		},
		{
			label: "Collection refuses unverified vendors",
			state: /domainVerified/.test(observe) ? "done" : "planned",
			detail: "observe/route.ts checks vendor.domainVerified before recording anything",
		},
		{
			label: "Self-serve vendor signup issues a domain-verification token",
			state: /set default/i.test(migrations) && /domain_verification_token/.test(migrations) ? "done" : "planned",
			detail: "domain_verification_token has a DB default — every insert gets one, not just onboarding's",
		},
		{
			label: "Fraud features (ASN distribution, hash counts)",
			state: /asn_distribution:\s*null/.test(fraud) ? "planned" : "done",
			detail: fraud
				? "fraud-features.ts still hardcodes these null — accepted gap, not wired to real ASN data yet"
				: "fraud-features.ts not found",
		},
		{
			label: "Tier 3 — Stripe/IdP corroboration",
			state: hasStripeDependency ? "partial" : "planned",
			detail: "no Stripe dependency in package.json — schema designed for it, not built",
		},
		{
			label: "Tier 4 — customer counter-signing",
			state: hasCustomerCountersignRoute ? "partial" : "planned",
			detail: "no customer-facing consent/counter-sign flow exists — customers.ts's countersign.ts is the vendor→Letterstory fraud RPC, not this",
		},
		{
			label: "Support / help infrastructure",
			state: hasSupportRoutes ? "done" : "planned",
			detail: "no support or help routes in src/app",
		},
	];
}

const ICON = { done: "✅", partial: "🟡", planned: "⬜" };

function renderBlock(checks) {
	const rows = checks
		.map((c) => `| ${ICON[c.state]} ${c.label} | ${c.detail} |`)
		.join("\n");
	return [
		START,
		"> **Build status** — regenerated from the code, not hand-maintained. Run `node scripts/gen-readme-status.mjs` after a change that should move a row; `npm test` fails if this block drifts from what the checks find.",
		"",
		"| | |",
		"|---|---|",
		rows,
		END,
	].join("\n");
}

export function currentBlock() {
	return renderBlock(runChecks());
}

export function applyToReadme(check = false) {
	const readme = readFileSync(README_PATH, "utf8");
	const startIdx = readme.indexOf(START);
	const endIdx = readme.indexOf(END);
	if (startIdx === -1 || endIdx === -1) {
		throw new Error(`README.md is missing the ${START} / ${END} markers`);
	}
	const before = readme.slice(0, startIdx);
	const after = readme.slice(endIdx + END.length);
	const next = `${before}${currentBlock()}${after}`;

	if (check) {
		return next === readme;
	}
	writeFileSync(README_PATH, next);
	return true;
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const check = process.argv.includes("--check");
	const upToDate = applyToReadme(check);
	if (check && !upToDate) {
		console.error("README.md's Build status block is stale — run `node scripts/gen-readme-status.mjs` and commit the result.");
		process.exit(1);
	}
}
